namespace Domain.Entities;

/// <summary>
/// Derives a product's type label (used for quick sub-filters inside a category)
/// from keywords in its name. First matching rule wins, so order matters.
/// </summary>
public static class ProductTypeClassifier
{
    private static readonly (string Type, string[] Keywords)[] Rules =
    [
        // Clothing
        ("Костюмы", ["костюм"]),
        ("Платья", ["плать", "сарафан"]),
        ("Комбинезоны", ["комбинезон"]),
        ("Пальто", ["пальто", "тренч"]),
        ("Куртки", ["куртк", "пуховик", "бомбер"]),
        ("Пиджаки и жакеты", ["пиджак", "жакет"]),
        ("Блузки", ["блузк"]),
        ("Рубашки", ["рубашк"]),
        ("Свитеры", ["джемпер", "свитер"]),
        ("Худи", ["худи"]),
        ("Брюки", ["брюки", "брюк"]),
        ("Футболки", ["футболк"]),
        ("Боди", ["боди"]),
        // Shoes
        ("Кроссовки", ["кроссовк"]),
        ("Ботинки", ["ботинк"]),
        // Kitchen & dishes (kettles before stoves: "Чайник для плиты")
        ("Чайники", ["чайник"]),
        ("Ножи", ["ножей", "нож "]),
        ("Кружки и чашки", ["кружек", "чашк", "чашек"]),
        ("Тарелки", ["тарел"]),
        ("Миски", ["миск", "мисок"]),
        ("Бокалы", ["бокал"]),
        ("Кастрюли", ["кастрюл"]),
        ("Кухонные аксессуары", ["органайзер", "принадлеж", "доска"]),
        // Appliances
        ("Микроволновки", ["микроволнов"]),
        ("Холодильники", ["холодильник"]),
        ("Плиты и духовки", ["плита", "духов"]),
        ("Наушники и колонки", ["наушник", "колонк"]),
        ("Тостеры", ["тостер"]),
        ("Вентиляторы", ["вентилятор"]),
        ("Кофемолки", ["кофемолк"]),
        ("Фены", ["фен "]),
        // Sport
        ("Штанги и диски", ["штанг", "диски"]),
        ("Гантели", ["гантел"]),
        ("Тренажёры", ["тренажёр", "скамья", "турник"]),
        ("Экипировка", ["шлем", "очки", "ракетка", "мяч", "коврик", "бутылка"]),
        // Bags & accessories
        ("Рюкзаки", ["рюкзак"]),
        ("Сумки", ["сумк"]),
        ("Украшения", ["колье", "цепочк", "браслет", "кольц", "колец", "кулон"]),
        ("Часы", ["часы"]),
        ("Чехлы", ["чехол"]),
    ];

    public static string? Infer(string? name)
    {
        if (string.IsNullOrWhiteSpace(name))
        {
            return null;
        }

        var padded = $"{name.ToLowerInvariant()} ";
        foreach (var (type, keywords) in Rules)
        {
            if (keywords.Any(padded.Contains))
            {
                return type;
            }
        }

        return null;
    }
}
